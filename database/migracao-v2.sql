        CONSTRAINT CK_RM2_Q2_CRESS_TOTAL CHECK (Q2_CRESS <= Q2_EFETIVOS + Q2_TERCEIRIZADOS + Q2_TEMPORARIOS + Q2_COMISSIONADOS),
        CONSTRAINT CK_RM2_Q3_EXCLUSIVOS_TOTAL CHECK (Q3_EXCLUSIVOS <= Q3_EFETIVOS + Q3_TERCEIRIZADOS + Q3_TEMPORARIOS + Q3_COMISSIONADOS),
        CONSTRAINT CK_RM2_Q6_OUTRA CHECK (
            (Q6_ESTRUTURA = 'OUTRA' AND LEN(LTRIM(RTRIM(ISNULL(Q6_OUTRA_DESCRICAO, N'')))) BETWEEN 3 AND 300)
            OR (Q6_ESTRUTURA <> 'OUTRA' AND Q6_OUTRA_DESCRICAO IS NULL)),
        CONSTRAINT CK_RM2_Q7_DETALHES CHECK (
            (Q7_PROGRAMA = 'PROPRIO' AND LEN(LTRIM(RTRIM(ISNULL(Q7_PROGRAMA_DETALHES, N'')))) BETWEEN 3 AND 2000)
            OR (Q7_PROGRAMA <> 'PROPRIO' AND Q7_PROGRAMA_DETALHES IS NULL))
    );
    CREATE INDEX IX_RespostasMunicipaisV2_CriadoEm ON dbo.RespostasMunicipaisV2(CriadoEm DESC);
