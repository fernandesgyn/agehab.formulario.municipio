IF OBJECT_ID(N'dbo.RespostasMunicipaisV2', N'U') IS NULL
BEGIN
    CREATE TABLE dbo.RespostasMunicipaisV2 (
        Id BIGINT IDENTITY(1,1) NOT NULL CONSTRAINT PK_RespostasMunicipaisV2 PRIMARY KEY,
        CodigoIBGE INT NOT NULL CONSTRAINT FK_RespostasV2_Municipios REFERENCES dbo.Municipios(CodigoIBGE),
        Q2_EFETIVOS INT NOT NULL CONSTRAINT CK_RM2_Q2_EFETIVOS CHECK (Q2_EFETIVOS BETWEEN 0 AND 100000),
        Q2_TERCEIRIZADOS INT NOT NULL CONSTRAINT CK_RM2_Q2_TERCEIRIZADOS CHECK (Q2_TERCEIRIZADOS BETWEEN 0 AND 100000),
        Q2_TEMPORARIOS INT NOT NULL CONSTRAINT CK_RM2_Q2_TEMPORARIOS CHECK (Q2_TEMPORARIOS BETWEEN 0 AND 100000),
        Q2_COMISSIONADOS INT NOT NULL CONSTRAINT CK_RM2_Q2_COMISSIONADOS CHECK (Q2_COMISSIONADOS BETWEEN 0 AND 100000),
        Q2_CRESS INT NOT NULL CONSTRAINT CK_RM2_Q2_CRESS CHECK (Q2_CRESS BETWEEN 0 AND 100000),
        Q3_EFETIVOS INT NOT NULL CONSTRAINT CK_RM2_Q3_EFETIVOS CHECK (Q3_EFETIVOS BETWEEN 0 AND 100000),
        Q3_TERCEIRIZADOS INT NOT NULL CONSTRAINT CK_RM2_Q3_TERCEIRIZADOS CHECK (Q3_TERCEIRIZADOS BETWEEN 0 AND 100000),
        Q3_TEMPORARIOS INT NOT NULL CONSTRAINT CK_RM2_Q3_TEMPORARIOS CHECK (Q3_TEMPORARIOS BETWEEN 0 AND 100000),
        Q3_COMISSIONADOS INT NOT NULL CONSTRAINT CK_RM2_Q3_COMISSIONADOS CHECK (Q3_COMISSIONADOS BETWEEN 0 AND 100000),
        Q3_EXCLUSIVOS INT NOT NULL CONSTRAINT CK_RM2_Q3_EXCLUSIVOS CHECK (Q3_EXCLUSIVOS BETWEEN 0 AND 100000),
        Q4_EFETIVOS INT NOT NULL CONSTRAINT CK_RM2_Q4_EFETIVOS CHECK (Q4_EFETIVOS BETWEEN 0 AND 100000),
        Q4_TERCEIRIZADOS INT NOT NULL CONSTRAINT CK_RM2_Q4_TERCEIRIZADOS CHECK (Q4_TERCEIRIZADOS BETWEEN 0 AND 100000),
        Q4_TEMPORARIOS INT NOT NULL CONSTRAINT CK_RM2_Q4_TEMPORARIOS CHECK (Q4_TEMPORARIOS BETWEEN 0 AND 100000),
        Q4_COMISSIONADOS INT NOT NULL CONSTRAINT CK_RM2_Q4_COMISSIONADOS CHECK (Q4_COMISSIONADOS BETWEEN 0 AND 100000),
        Q5_CRESS_COORDENACAO INT NOT NULL CONSTRAINT CK_RM2_Q5_CRESS_COORDENACAO CHECK (Q5_CRESS_COORDENACAO BETWEEN 0 AND 100000),
        Q5_AREAS_AFINS INT NOT NULL CONSTRAINT CK_RM2_Q5_AREAS_AFINS CHECK (Q5_AREAS_AFINS BETWEEN 0 AND 100000),
        Q5_ADMINISTRATIVOS INT NOT NULL CONSTRAINT CK_RM2_Q5_ADMINISTRATIVOS CHECK (Q5_ADMINISTRATIVOS BETWEEN 0 AND 100000),
        Q6_ESTRUTURA VARCHAR(40) NOT NULL CONSTRAINT CK_RM2_Q6_ESTRUTURA CHECK (Q6_ESTRUTURA IN (
            'SECRETARIA_EXCLUSIVA','SECRETARIA_MISTA','SUPERINTENDENCIA','DIRETORIA',
            'GERENCIA_COORDENACAO','DEPARTAMENTO_SETOR','VINCULADA_OUTRA','SEM_ESTRUTURA','OUTRA')),
        Q6_OUTRA_DESCRICAO NVARCHAR(300) NULL,
        Q7_PROGRAMA VARCHAR(16) NOT NULL CONSTRAINT CK_RM2_Q7_PROGRAMA CHECK (Q7_PROGRAMA IN ('PROPRIO','ESTADUAL','FEDERAL','AMBOS')),
        Q7_PROGRAMA_DETALHES NVARCHAR(2000) NULL,
        Q8_01 BIT NOT NULL,
        Q8_02 BIT NOT NULL,
        Q8_03 BIT NOT NULL,
        Q8_04 BIT NOT NULL,
        Q8_05 BIT NOT NULL,
        Q8_06 BIT NOT NULL,
        Q8_07 BIT NOT NULL,
        Q8_08 BIT NOT NULL,
        Q8_09 BIT NOT NULL,
        Q8_10 BIT NOT NULL,
        Q8_11 BIT NOT NULL,
        Q8_12 BIT NOT NULL,
        Q8_13 BIT NOT NULL,
